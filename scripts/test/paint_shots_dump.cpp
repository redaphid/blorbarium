// Writes 1 in N frames of scripts/test/paint_shots.h, in runs of 4 in a row
// (a tick and the three after it, as the badge draws them: what one frame can
// keep for the next shows), as the bytes of its
// Appearance, with the hash the host draws them to, for the board build of the
// bench (paint_bench_s3.cpp), which cannot afford to live the pets itself under
// the emulator. Appearance is plain data with no pointer and nothing wider
// than 32 bits, so the S3 lays it out as the host does; the board side checks
// its size and two offsets against the ones written here.
//   built and run by scripts/test/paint_bench_qemu.sh
#include <cstddef>
#include <cstdio>
#include <cstdlib>

#include "paint/sprite_pack.h"
#include "paint_shots.h"

namespace {

uint64_t fnv(const paint::Canvas240& cv, uint64_t h) {
  const auto* b = reinterpret_cast<const uint8_t*>(cv.px);
  for (size_t i = 0; i < sizeof cv.px; ++i) h = (h ^ b[i]) * 0x100000001B3ull;
  return h;
}

}  // namespace

int main(int argc, char** argv) {
  if (argc < 3) return std::fprintf(stderr, "usage: paint_shots_dump <every> <out.inc>\n"), 2;
  const size_t every = size_t(std::atoi(argv[1]));
  FILE* out = std::fopen(argv[2], "w");
  if (!out || !every) return 1;
  static paint::Canvas240 cv;
  const std::vector<blorb::Appearance> shots = paintbench::dishShots();
  const std::vector<paint::DuelScene> duels = paintbench::duelShots();
  uint64_t dishHash = 0xCBF29CE484222325ull, duelHash = dishHash;
  size_t n = 0;
  std::fprintf(out, "// GENERATED by scripts/test/paint_shots_dump.cpp: 4 frames in a row of every %zu of paint_shots.h.\n",
               4 * every);
  std::fprintf(out, "constexpr size_t kShotBytes = %zu, kShotLineAt = %zu, kShotHangAt = %zu;\n", sizeof(blorb::Appearance),
               offsetof(blorb::Appearance, line), offsetof(blorb::Appearance, hangCharge));
  std::fprintf(out, "struct Shot { uint32_t now; uint8_t bytes[kShotBytes]; };\n");
  std::fprintf(out, "const Shot kShots[] = {\n");
  for (size_t i = 0; i < shots.size(); i += i % 4 == 3 ? 4 * every - 3 : 1, ++n) {
    const uint32_t now = uint32_t(i * 40);
    const blorb::Appearance& a = shots[i];
    paint::draw(a, paint::packFor(a.species), cv, now);
    paint::drawBootHint(cv, paint::rimHint(a.boot));
    paint::drawIdleBar(cv, uint16_t(now / 7 % 1001));
    dishHash = fnv(cv, dishHash);
    std::fprintf(out, "  {%u, {", now);
    const auto* b = reinterpret_cast<const uint8_t*>(&a);
    for (size_t k = 0; k < sizeof a; ++k) std::fprintf(out, "%u,", b[k]);
    std::fprintf(out, "}},\n");
  }
  std::fprintf(out, "};\n");
  for (const paint::DuelScene& sc : duels) {
    paint::drawDuel(sc, paint::packFor(sc.me.look.species), paint::packFor(sc.them.look.species), cv, 0);
    duelHash = fnv(cv, duelHash);
  }
  std::fprintf(out, "constexpr uint64_t kDishHash = 0x%016llxull, kDuelHash = 0x%016llxull;\n", (unsigned long long)dishHash,
               (unsigned long long)duelHash);
  std::fclose(out);
  std::printf("shots=%zu duels=%zu dish_hash=%016llx duel_hash=%016llx\n", n, duels.size(), (unsigned long long)dishHash,
              (unsigned long long)duelHash);
  return 0;
}
